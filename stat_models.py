import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

# Memuat data Kota Bandung
df_pe = pd.read_csv("KOTA BANDUNG.csv")

# Mengambil data dari DataFrame
tahun = df_pe["Tahun"]
bm_infrastruktur = df_pe["bm_infrastruktur"]
bm_ekonomi = df_pe["bm_ekonomi"]
nilai_y = df_pe["PE"]  # Variabel dependen Y

# Melakukan regresi linear dengan matriks
X = np.column_stack(
    (bm_infrastruktur, bm_ekonomi)
)  # Matriks X dengan variabel independen
X = np.column_stack(
    (np.ones(len(tahun)), X)
)  # Tambahkan kolom untuk intercept (Beta 0)
beta = (
    np.linalg.inv(X.T @ X) @ X.T @ nilai_y
)  # Hitung parameter beta (koefisien regresi)

print("Koefisien Regresi:")
for i in range(len(beta)):
  print(f"Beta{i}: {beta[i]}")

# Plotting data aktual dan hasil regresi
fig, ax = plt.subplots()
ax.scatter(tahun, nilai_y, color="blue", label="Data Aktual (PE)")
ax.plot(
    tahun, X @ beta, color="red", label="Hasil Regresi"
)  # Garis hasil prediksi regresi
ax.set_xlabel("Tahun")
ax.set_ylabel("PE")
ax.legend()
plt.show()

