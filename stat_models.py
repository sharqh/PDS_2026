"""#UJI NORMALITAS

# Uji Normalitas Residual Regresi

Dalam analisis regresi, asumsi normalitas mengharuskan nilai **residual** (bukan variabel independen atau dependen secara terpisah) berdistribusi normal.

Di bawah ini adalah kode untuk menghitung residual, melakukan uji statistik Jarque-Bera, serta memplot grafik Q-Q Plot dan Histogram.
"""

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import scipy.stats as stats
import statsmodels.api as sm

# Membuat ulang DataFrame dan mendefinisikan model agar variabel 'results' tersedia
dataku = {
    "Partisipan": np.arange(1, 11),
    "Peng Makanan": [50, 40, 60, 55, 45, 65, 70, 75, 80, 90],
    "Peng Transportasi": [20, 25, 30, 35, 40, 50, 55, 60, 65, 70],
    "Berat Badan": [60, 55, 65, 70, 62, 75, 80, 85, 90, 95]
}
df = pd.DataFrame(dataku)

X = df[["Peng Makanan", "Peng Transportasi"]]
y = df["Berat Badan"]
X = sm.add_constant(X)

model = sm.OLS(y, X)
results = model.fit()

# Menghitung Residual
residual = results.resid
df["Residual"] = residual

# Uji Formal Normalitas (Jarque-Bera)
jb_stat, jb_p_value = stats.jarque_bera(residual)

print("=" * 60)
# UJI FORMAL NORMALITAS (JARQUE-BERA)
print(f"Statistik Jarque-Bera : {jb_stat:.4f}")
print(f"p-value               : {jb_p_value:.4f}")
print("-" * 60)
if jb_p_value > 0.05:
    print("Kesimpulan: Residual berdistribusi NORMAL (p-value > 0.05)")
else:
    print("Kesimpulan: Residual TIDAK berdistribusi normal (p-value <= 0.05)")
print("=" * 60)

# Visualisasi Deteksi Normalitas
fig, axes = plt.subplots(1, 2, figsize=(14, 5))

# Grafik 1: Histogram Residual + Kurva Normal
sns_installed = True
try:
    import seaborn as sns
    sns.histplot(residual, kde=True, ax=axes[0], color='skyblue', edgecolor='black')
except ImportError:
    # Fallback jika seaborn tidak terpasang
    axes[0].hist(residual, bins=5, edgecolor='black', alpha=0.7, density=True, color='skyblue')
    # Tambahkan estimasi kurva kepadatan sederhana
    xmin, xmax = axes[0].get_xlim()
    x_axis = np.linspace(xmin, xmax, 100)
    y_axis = stats.norm.pdf(x_axis, np.mean(residual), np.std(residual))
    axes[0].plot(x_axis, y_axis, color='red', linewidth=2)

# Grafik 2: Q-Q Plot (Normal Probability Plot)
sm.qqplot(residual, line='s', ax=axes[1])
