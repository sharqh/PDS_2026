import seaborn as sns
import numpy as np
import pandas as pd

# Muat dataset (2)
df_fiskal = pd.read_csv("https://raw.githubusercontent.com/Alam-A99/DATAAKSI/refs/heads/main/dataset_fiskal_97_hipoFull.csv")
df_fiskal

# Point Plot (Tren Rata-rata per Tahun)
plt.figure(figsize=(8, 4))
sns.pointplot(data=df_fiskal, x="Tahun", y="KEMISKINAN",
              color="green", marker="D")
plt.title("Tren Rata-rata Kemiskinan per Tahun")
plt.xticks(rotation=0)
plt.tight_layout()
plt.show()

# Distribusi & Hubungan Sederhana
plt.figure(figsize=(8, 4))
sns.histplot(data=df_fiskal, x="KEMISKINAN", bins=30, kde=True, color="navy")
plt.title("Distribusi Tingkat Kemiskinan di Seluruh Daerah")
plt.xlabel("Tingkat Kemiskinan (%)")
plt.ylabel("Frekuensi (Jumlah Daerah)")
plt.tight_layout()
plt.show()