from matplotlib import pyplot as plt
import seaborn as sns
import numpy as np
import pandas as pd

# Muat dataset (1)
df_penjualan = pd.read_csv("https://raw.githubusercontent.com/Alam-A99/Pandas_Latih/10ebb3af000e930a44989075733f495d5c2f4be5/penjualan.csv")
df_penjualan

# Membersihkan nama kolom terlebih dahulu
df_penjualan.columns = df_penjualan.columns.str.strip()

# Menambah Kolom baru "total"
df_penjualan["total"] = df_penjualan[['jan','feb','mar','apr']].sum(axis=1)
df_penjualan

# Membuat Bar Chart Per Orang
plt.figure(figsize=(8, 4))
df_sorted = df_penjualan.sort_values("total", ascending=False)
sns.barplot(data=df_sorted, x="nama", y="total", palette="viridis")
plt.title("Total Penjualan per Orang")
plt.xticks(rotation=0)
plt.tight_layout()
plt.show()

